test('bağımsız Artifact önizlemesinde geçici arşiv ve JSON dönüştürme',async({page},testInfo)=>{
  await page.goto(pathToFileURL(resolve('work-artifact/kartvizit-artifact.html')).href)
  await expect(page.getByRole('heading',{name:'Kartvizit çalışma alanı'})).toBeVisible()
  await expect(page.getByText(/Geçici oturum/)).toBeVisible()
  await expect(page.getByText(/görsel analizi bağlı değil/)).toBeVisible()
  if(process.env.KARTVIZIT_SCREENSHOTS)await page.screenshot({path:testInfo.outputPath('artifact.png'),fullPage:true})
  await page.getByLabel('Claude analiz JSON’u').fill(JSON.stringify({cards:[{fullName:'Deniz Örnek',company:'Örnek Teknoloji',emailAddresses:['deniz@example.test'],uncertain:['department']}]}))
  await page.getByRole('button',{name:'Sonucu incele'}).click()
  await expect(page.getByText('Şüpheli alanlar: department')).toBeVisible()
  await page.getByLabel('Unvan',{exact:true}).fill('Tasarım Direktörü')
  await page.getByRole('button',{name:'Kaydı önizle'}).click()
  await page.getByRole('button',{name:'Arşive kaydet'}).click()
  await expect(page.getByText(/Eklenen 1/)).toBeVisible()
  const output=page.waitForEvent('download')
  await page.getByRole('button',{name:'JSON indir',exact:true}).click()
  const cards=JSON.parse(await readFile((await (await output).path())!,'utf8')).cards
  expect(cards[0]).toMatchObject({fullName:'Deniz Örnek',jobTitle:'Tasarım Direktörü',rawOcrText:''})
  expect(cards[0]).not.toHaveProperty('photos')
  await page.getByRole('button',{name:'Arşiv',exact:true}).click()
  await expect(page.getByText('Deniz Örnek',{exact:true})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'Arşiv',exact:true}).click()
  await expect(page.getByText('Gösterilecek kart yok.')).toBeVisible()

  // The identical bytes are imported in the PWA, then a PWA export is opened here.
  await home(page)
  await nav(page,'Tara').click()
  await page.getByRole('button',{name:/^Claude ile Tara/}).click()
  const transferJson=JSON.stringify({format:'kartvizit',version:1,cards})
  await page.getByLabel('Claude JSON dosyası').setInputFiles({name:'artifact.json',mimeType:'application/json',buffer:Buffer.from(transferJson)})
  await page.getByRole('button',{name:'Arşive aktar',exact:true}).click()
  await expect(page.getByText(/Eklenen: 1/)).toBeVisible()
  const returnFile=page.waitForEvent('download')
  await page.getByRole('button',{name:'JSON indir',exact:true}).click()
  const returnBytes=await readFile((await (await returnFile).path())!)
  await page.goto(pathToFileURL(resolve('work-artifact/kartvizit-artifact.html')).href)
  await page.getByRole('button',{name:'JSON aktarımı',exact:true}).click()
  await page.getByLabel('JSON dosyası',{exact:true}).setInputFiles({name:'return.json',mimeType:'application/json',buffer:returnBytes})
  await page.getByRole('button',{name:'Arşive kaydet',exact:true}).click()
  await expect(page.getByText(/Eklenen 1/)).toBeVisible()
})
