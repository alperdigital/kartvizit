import { expect,test,type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

const fixture=async(page:Page,lines:string[])=>Buffer.from(await page.evaluate(lines=>{
  const canvas=document.createElement('canvas')
  canvas.width=1420;canvas.height=700
  const ctx=canvas.getContext('2d')!
  ctx.fillStyle='#fff';ctx.fillRect(0,0,1420,700);ctx.fillStyle='#000'
  lines.forEach((line,i)=>{ctx.font=(i===0?'bold 70px':'48px')+' Arial';ctx.fillText(line,80,130+i*105)})
  return canvas.toDataURL('image/png').split(',')[1]
},lines),'base64')
const nav=(page:Page,name:string)=>page.getByRole('navigation').getByRole('button',{name,exact:true}).filter({visible:true})
const home=async(page:Page)=>{
  await page.goto('/kartvizit/')
  await expect(page.getByRole('heading',{name:'Kartvizitler',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(await page.evaluate(()=>innerWidth))
}
const create=async(page:Page,name:string)=>{
  await page.getByRole('button',{name:'Manuel ekle',exact:true}).click()
  await page.getByLabel('Tam ad',{exact:true}).fill(name)
  await page.getByLabel('Şirket',{exact:true}).fill('Örnek Teknoloji')
  await page.getByRole('button',{name:'Kaydet',exact:true}).click()
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Arşive dön'}).click()
}
test('yerel arşiv, düzenleme, favori, arama, çoklu işlemler ve yedek',async({page})=>{
  await home(page)
  await create(page,'Çağrı Şahin')
  await create(page,'Örnek Işık')
  await page.getByRole('button',{name:'Favori Çağrı Şahin'}).click()
  await nav(page,'Favoriler').click()
  await expect(page.getByRole('button',{name:/Çağrı Şahin Örnek/})).toBeVisible()
  await nav(page,'Kartvizitler').click()
  await page.getByRole('searchbox').fill('cagri sahin')
  await expect(page.getByRole('button',{name:/Örnek Işık Örnek/})).toHaveCount(0)
  await page.getByRole('button',{name:/Çağrı Şahin Örnek/}).click()
  await page.getByRole('button',{name:'Düzenle'}).click()
  await page.getByLabel('Notlar',{exact:true}).fill('Görüşme planlandı')
  await page.getByRole('button',{name:'Kaydet',exact:true}).click()
  await expect(page.getByText('Görüşme planlandı')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button',{name:/Çağrı Şahin Örnek/})).toBeVisible()
  await page.getByRole('button',{name:'Çoklu seçim'}).click()
  await page.getByRole('button',{name:'Tümünü seç'}).click()
  await page.getByRole('button',{name:'Etiketle'}).click()
  await page.getByRole('dialog').getByRole('textbox').fill('İş bağlantısı')
  await page.getByRole('button',{name:'Etiketleri ekle'}).click()
  await page.getByLabel('Etiketler',{exact:true}).selectOption('İş bağlantısı')
  await expect(page.getByText('2 seçildi')).toBeVisible()
  await page.getByRole('button',{name:'Dışa aktar',exact:true}).last().click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'JSON',exact:true}).click()
  const file=await download
  const bytes=await readFile((await file.path())!)
  expect(JSON.parse(bytes.toString()).cards).toHaveLength(2)
  await page.getByRole('button',{name:'Dışa aktar ×'}).click()
  await page.getByRole('button',{name:'Sil',exact:true}).click()
  await page.getByRole('button',{name:'Kalıcı sil',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Henüz kartvizit yok'})).toBeVisible()
  await nav(page,'Ayarlar').click()
  await page.getByLabel('Yedek dosyası').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:bytes})
  await expect(page.getByText('2 kayıt eklendi, 0 mevcut kayıt korundu.')).toBeVisible()
  await nav(page,'Kartvizitler').click()
  await expect(page.getByRole('button',{name:/Çağrı Şahin Örnek/})).toBeVisible()
})
test('gerçek Türkçe ve İngilizce OCR, çevrimdışı kabuk ve dosya çıktısı',async({page,context})=>{
  await home(page)
  const manifest=await page.request.get('/kartvizit/manifest.webmanifest')
  expect((await manifest.json()).scope).toBe('/kartvizit/')
  await nav(page,'Tara').click()
  await page.getByRole('button',{name:'OCR kaynaklarını indir'}).click()
  await expect(page.getByText('Çevrimdışı tarama hazır',{exact:true})).toBeVisible({timeout:60_000})
  const tur=await fixture(page,['ÖRNEK ŞAHİN','GENEL MÜDÜR','ÖRNEK TEKNOLOJİ','hello@example.test'])
  const eng=await fixture(page,['SAMPLE CONTACT','FOUNDER','EXAMPLE STUDIO','sample@example.test'])
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText('Çevrimdışı',{exact:true})).toBeVisible()
  await nav(page,'Tara').click()
  await page.getByLabel('Kartvizit görselleri').setInputFiles([
    {name:'tur.png',mimeType:'image/png',buffer:tur},{name:'eng.png',mimeType:'image/png',buffer:eng},
  ])
  await page.getByRole('button',{name:'Taramayı başlat'}).click()
  const review=page.getByRole('button',{name:'Sonucu incele'})
  await expect(review).toHaveCount(2,{timeout:95_000})
  await review.first().click()
  await expect(page.getByLabel('Tam ad',{exact:true})).toHaveValue(/ÖRNEK ŞAHİN/i)
  await expect(page.getByLabel('Mesleki unvan')).toHaveValue(/GENEL MÜDÜR/i)
  await page.getByLabel('Tam ad',{exact:true}).fill('Örnek Şahin')
  await page.getByRole('button',{name:'Kaydet',exact:true}).click()
  await review.click()
  await expect(page.getByLabel('Tam ad',{exact:true})).toHaveValue(/SAMPLE CONTACT/i)
  await expect(page.getByLabel('Mesleki unvan')).toHaveValue('FOUNDER')
  await page.getByRole('button',{name:'Kaydet',exact:true}).click()
  await nav(page,'Kartvizitler').click()
  await page.getByRole('searchbox').fill('ornek sahin')
  await expect(page.getByRole('button',{name:/Örnek Şahin GENEL/})).toBeVisible()
  await page.getByRole('button',{name:/Örnek Şahin GENEL/}).click()
  await page.getByRole('button',{name:'Düzenle'}).click()
  await page.getByLabel('Notlar',{exact:true}).fill('Çevrimdışı düzenlendi')
  await page.getByRole('button',{name:'Kaydet',exact:true}).click()
  await expect(page.getByText('Çevrimdışı düzenlendi')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button',{name:/Örnek Şahin GENEL/})).toBeVisible()
  await page.getByRole('button',{name:'Dışa aktar',exact:true}).click()
  for(const [name,suffix] of [['CSV','.csv'],['Excel','.xlsx'],['vCard','.vcf']]){
    const event=page.waitForEvent('download')
    await page.getByRole('button',{name,exact:true}).click()
    expect((await event).suggestedFilename()).toContain(suffix)
  }
})

